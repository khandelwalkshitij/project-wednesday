# Writes src/data/dop853-coefficients.js from SciPy's copy of Hairer's DOP853 tables
# (scipy.integrate._ivp.dop853_coefficients, BSD licence). Usage: python3 tools/gen_dop853.py
import json
import scipy
import scipy.integrate._ivp.dop853_coefficients as d

def arr(a):
    return json.dumps([float(x) if not hasattr(x, '__len__') else [float(v) for v in x] for x in a], separators=(',', ':'))

assert d.N_STAGES == 12 and d.N_STAGES_EXTENDED == 16 and d.INTERPOLATOR_POWER == 7
out = [
    '// DOP853 Butcher tableau, error estimators and dense-output coefficients (Hairer, Norsett, Wanner).',
    '// Generated by tools/gen_dop853.py from SciPy ' + scipy.__version__ + ' (scipy.integrate._ivp.dop853_coefficients).',
    'export var N_STAGES = 12, N_STAGES_EXTENDED = 16, INTERPOLATOR_POWER = 7;',
    'export var A = ' + arr(d.A) + ';',
    'export var B = ' + arr(d.B) + ';',
    'export var C = ' + arr(d.C) + ';',
    'export var E3 = ' + arr(d.E3) + ';',
    'export var E5 = ' + arr(d.E5) + ';',
    'export var D = ' + arr(d.D) + ';',
]
open('src/data/dop853-coefficients.js', 'w').write('\n'.join(out) + '\n')
print('A', d.A.shape, 'B', d.B.shape, 'C', d.C.shape, 'E3', d.E3.shape, 'E5', d.E5.shape, 'D', d.D.shape)

# Test truth: a Kepler orbit (e = 0.1) over 10 periods with SciPy's own DOP853, for tests/core/adaptive.test.mjs
import numpy as np
from scipy.integrate import solve_ivp
mu, a, e = 3.986004418e14, 7e6, 0.1
T = 2 * np.pi * np.sqrt(a**3 / mu); rp = a * (1 - e); vp = np.sqrt(mu * (1 + e) / rp)
def f(t, y):
    return np.concatenate([y[3:], -mu / np.linalg.norm(y[:3])**3 * y[:3]])
truth = {'mu': mu, 'y0': [rp, 0, 0, 0, vp, 0], 't_end': 10 * T, 't_dense': 3.3 * T, 'atol': 1e-6, 'runs': []}
for rtol in [1e-8, 1e-10, 1e-12]:
    s = solve_ivp(f, (0, 10 * T), truth['y0'], method='DOP853', rtol=rtol, atol=1e-6, dense_output=True)
    truth['runs'].append({'rtol': rtol, 'steps': int(len(s.t) - 1), 'end': s.y[:, -1].tolist(), 'dense': s.sol(3.3 * T).tolist()})
open('tests/fixtures/dop853_truth.json', 'w').write(json.dumps(truth) + '\n')
print('tests/fixtures/dop853_truth.json', [r['steps'] for r in truth['runs']])
