# Writes src/data/nrlmsise00-data.js from Dominik Brodowski's public-domain C port (nrlmsise-00_data.c, e.g. from the
# nrlmsise00 PyPI sdist), and tests/fixtures/msis_truth.json from pymsis (NRL's original Fortran NRLMSISE-00, version=0).
# Usage: python3 tools/gen_nrlmsise00.py <path to nrlmsise-00_data.c>. Needs numpy and pymsis.
import json, re, sys
import numpy as np
import pymsis

s = open(sys.argv[1]).read()
s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
NUM = r'[-+]?\d+\.?\d*(?:[eE][-+]?\d+)?'
arrays = {}
for m in re.finditer(r'double\s+(\w+)((?:\[\d+\])+)\s*=\s*\{', s):
    dims = [int(x) for x in re.findall(r'\[(\d+)\]', m.group(2))]
    depth, i = 0, m.end() - 1
    while True:
        if s[i] == '{': depth += 1
        elif s[i] == '}':
            depth -= 1
            if depth == 0: break
        i += 1
    body = s[m.end() - 1:i + 1]
    if len(dims) == 1:
        v = [float(x) for x in re.findall(NUM, body)]
        arrays[m.group(1)] = v + [0.0] * (dims[0] - len(v))
    else:
        rows = [[float(x) for x in re.findall(NUM, b)] for b in re.findall(r'\{([^{}]*)\}', body[1:-1])]
        assert len(rows) == dims[0] and all(len(r) == dims[1] for r in rows), m.group(1)
        arrays[m.group(1)] = rows
assert set(arrays) == {'pt', 'pd', 'ps', 'pdl', 'ptm', 'pdm', 'ptl', 'pma', 'sam', 'pavgm'}, sorted(arrays)
arrays['ptm'] = arrays['ptm'][:10]
with open('src/data/nrlmsise00-data.js', 'w') as f:
    f.write('// NRLMSISE-00 coefficients (Picone, Hedin, Drob, Aikin 2002), from the C port by Dominik Brodowski (public domain).\n')
    f.write('// Generated by tools/gen_nrlmsise00.py. U.S. Government work: the original NRL Fortran is in the public domain and\n')
    f.write('// not subject to copyright protection (17 U.S.C. 105, 403). No endorsement by or affiliation with the Naval Research Laboratory is implied.\n')
    for k in ['pt', 'pd', 'ps', 'pdl', 'ptm', 'pdm', 'ptl', 'pma', 'sam', 'pavgm']:
        f.write('export var ' + k.upper() + ' = ' + json.dumps(arrays[k], separators=(',', ':')) + ';\n')

# truth: a spread of altitudes, latitudes, longitudes, times and solar/geomagnetic conditions; daily-Ap and 3-hour-ap modes
rng = np.random.default_rng(2002)
cases = []
for k in range(120):
    alt = [0.5, 15, 40, 70, 85, 95, 110, 130, 160, 200, 250, 300, 400, 500, 650, 800, 1000][k % 17] if k < 68 else float(rng.uniform(80, 1000))
    doy = int(rng.integers(1, 366)); sec = float(rng.uniform(0, 86400)); lat = float(rng.uniform(-89, 89)); lon = float(rng.uniform(-180, 180))
    f107 = float(rng.uniform(65, 300)); f107a = float(np.clip(f107 + rng.normal(0, 20), 65, 300))
    aps = [float(rng.choice([2, 4, 7, 15, 27, 48, 80, 132, 207, 300])) for _ in range(7)]
    mode = 'ap_array' if k % 3 == 2 else 'daily'
    cases.append(dict(year=2010, doy=doy, sec=sec, alt=alt, lat=lat, lon=lon, f107=f107, f107a=f107a, ap=aps if mode == 'ap_array' else [aps[0]] * 7, mode=mode))
for c in cases:
    date = np.datetime64('2010-01-01T00:00') + np.timedelta64(c['doy'] - 1, 'D') + np.timedelta64(int(round(c['sec'] * 1e6)), 'us')
    opts = [1] * 25
    if c['mode'] == 'ap_array': opts[8] = -1
    out = pymsis.calculate(np.array([date]), np.array([c['lon']]), np.array([c['lat']]), np.array([c['alt']]),
                           np.array([c['f107']]), np.array([c['f107a']]), np.array([c['ap']]), options=opts, version=0)
    o = np.squeeze(out)
    c['sec'] = float((date - np.datetime64('2010-01-01T00:00') - np.timedelta64(c['doy'] - 1, 'D')) / np.timedelta64(1, 's'))
    c['rho'] = float(o[pymsis.Variable.MASS_DENSITY]); c['T'] = float(o[pymsis.Variable.TEMPERATURE])
    c['n'] = {name: (None if np.isnan(v) else v) for name, v in ((n, float(o[getattr(pymsis.Variable, n)])) for n in ['N2', 'O2', 'O', 'HE', 'H', 'AR', 'N', 'ANOMALOUS_O'])}
json.dump(cases, open('tests/fixtures/msis_truth.json', 'w'), allow_nan=False)
print('NRLMSISE-00 data written;', len(cases), 'truth cases')
