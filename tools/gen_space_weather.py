# Writes src/data/space-weather.js from CelesTrak's SW-All.txt (https://celestrak.org/SpaceData/SW-All.txt; CelesTrak asks
# only that the URL be cited). Usage: python3 tools/gen_space_weather.py <path to SW-All.txt>
# Download a fresh SW-All.txt from CelesTrak and rerun this to update the bundled table.
#
# Daily records from 1971-12-01 (MSIS needs 57 h of ap history before a 1972 epoch) through the end of CelesTrak's daily
# predictions, 15 characters each: eight 3-hour ap values (1 char each, index into AP_LEVELS), daily Ap (2 chars),
# observed F10.7 x 10 (3 chars), observed 81-day centred mean x 10 (2 chars). Numbers are base 91 over ASCII 35..126 without '\'.
# Monthly predictions (F10.7 and its 81-day mean, no Ap) follow as a plain list.
import collections, datetime, json, sys

W = [4, 3, 3, 5, 3] + [3] * 8 + [4] + [4] * 8 + [4, 4, 2, 4, 6, 2, 6, 6, 6, 6, 6]
def parse(line):
    out, i = [], 0
    for w in W: out.append(line[i:i + w].strip()); i += w
    return out

text = open(sys.argv[1]).read()
updated = next(l[8:].strip() for l in text.split('\n') if l.startswith('UPDATED '))
sec, rows = None, collections.defaultdict(list)
for l in text.split('\n'):
    if l.startswith('BEGIN '): sec = l[6:].strip(); continue
    if l.startswith('END '): sec = None; continue
    if sec and l.strip(): rows[sec].append(parse(l))

ALPHA = ''.join(chr(c) for c in range(35, 127) if c != 92)
assert len(ALPHA) == 91
def enc(v, n):
    assert 0 <= v < 91 ** n, (v, n)
    s = ''
    for _ in range(n): s = ALPHA[v % 91] + s; v //= 91
    return s
AP_LEVELS = sorted({0, 2, 3, 4, 5, 6, 7, 9, 12, 15, 18, 22, 27, 32, 39, 48, 56, 67, 80, 94, 111, 132, 154, 179, 207, 236, 300, 400, 8, 10, 20})
def day_number(y, m, d): return (datetime.date(y, m, d) - datetime.date(2000, 1, 1)).days

daily = [r for r in rows['OBSERVED'] + rows['DAILY_PREDICTED'] if (int(r[0]), int(r[1])) >= (1971, 12)]
dn = [day_number(int(r[0]), int(r[1]), int(r[2])) for r in daily]
assert dn == list(range(dn[0], dn[0] + len(dn))), 'daily records must be consecutive'
out = []
for r in daily:
    aps = [int(v) for v in r[14:22]]
    out.append(''.join(ALPHA[AP_LEVELS.index(a)] for a in aps) + enc(int(r[22]), 2) + enc(round(float(r[30]) * 10), 3) + enc(round(float(r[31]) * 10), 2))
monthly = [[int(r[0]), int(r[1]), float(r[30]), float(r[31])] for r in rows['MONTHLY_PREDICTED']]
last_obs = rows['OBSERVED'][-1]
meta = {'source': 'CelesTrak SW-All.txt, https://celestrak.org/SpaceData/', 'updated': updated, 'firstDay': dn[0], 'days': len(dn),
        'lastObservedDay': day_number(int(last_obs[0]), int(last_obs[1]), int(last_obs[2])), 'apLevels': AP_LEVELS, 'alphabet': ALPHA}
with open('src/data/space-weather.js', 'w') as f:
    f.write('// Space weather from ' + meta['source'] + ' (updated ' + updated + '). Generated by tools/gen_space_weather.py.\n')
    f.write('// Daily: 3-hour ap, daily Ap, observed F10.7 and its 81-day centred mean; observed to the date in SW_META, then CelesTrak predictions.\n')
    f.write('export var SW_META = ' + json.dumps(meta, separators=(',', ':')) + ';\n')
    f.write('export var SW_MONTHLY = ' + json.dumps(monthly, separators=(',', ':')) + ';   // [year, month, F10.7, 81-day mean], predicted\n')
    f.write('export var SW_DAILY = "' + ''.join(out) + '";\n')
print('days', len(dn), 'from', daily[0][:3], 'to', daily[-1][:3], '| observed to', last_obs[:3], '| monthly', monthly[0][:2], '-', monthly[-1][:2], '| updated', updated)
