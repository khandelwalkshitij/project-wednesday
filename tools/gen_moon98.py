# Writes src/data/moon98-series.js (the Meeus lunar series as tabulated in ERFA moon98.c) and tests/fixtures/moon_truth.json
# (positions from pyerfa's erfa.moon98). Usage: python3 tools/gen_moon98.py <path to erfa/src>. Needs pyerfa.
import json, re, sys
import erfa
E = sys.argv[1]
src = open(f"{E}/moon98.c").read()

def table(name, width):
    blk = src[src.index(f"{name}[] = {{"):]
    blk = blk[:blk.index("};")]
    rows = [[float(v) for v in m.split(",")] for m in re.findall(r"\{([^{}]+)\}", blk[blk.index("{") + 1:])]
    assert all(len(r) == width for r in rows), name
    return [[int(v) for v in r[:4]] + r[4:] for r in rows]

tlr, tb = table("tlr", 6), table("tb", 5)
assert len(tlr) == 60 and len(tb) == 60, (len(tlr), len(tb))
with open("src/data/moon98-series.js", "w") as f:
    f.write("// Meeus lunar series (Astronomical Algorithms ch. 47) as tabulated in ERFA moon98.c. Generated by tools/gen_moon98.py.\n")
    f.write("// [D, M, M', F, longitude coefficient (deg), distance coefficient (m)] and [D, M, M', F, latitude coefficient (deg)].\n")
    f.write("export var MOON_LR = " + json.dumps(tlr, separators=(",", ":")) + ";\n")
    f.write("export var MOON_B = " + json.dumps(tb, separators=(",", ":")) + ";\n")

# truth: erfa.moon98 at TT = J2000 + t seconds, spread over 1980-2060
ts = [(-20 + 80 * k / 39) * 365.25 * 86400 + 3600 * k * 1.37 for k in range(40)]
truth = []
for t in ts:
    pv = erfa.moon98(erfa.DJ00, t / 86400.0)
    truth.append({"tt": t, "r": [float(v) * erfa.DAU for v in pv["p"]]})
json.dump(truth, open("tests/fixtures/moon_truth.json", "w"))
print("moon98:", len(tlr), "+", len(tb), "terms;", len(truth), "truth points")
