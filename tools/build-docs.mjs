// Builds the in-app documentation from docs/*.md, so the Markdown files are the single source:
//   src/viewer/docs-content.js   the Documentation tab (models, config reference, accuracy and limits, glossary)
//   index.html                   the "Config fields" list under the JSON box, from the config reference's field summary
// Usage: node tools/build-docs.mjs          write both
//        node tools/build-docs.mjs --check  exit 1 if either is out of date (run by the test suite)
// Handles the Markdown these pages use: headings, paragraphs, lists, tables, fenced code, inline code, bold, italics,
// links and inline HTML. Links between pages become in-tab anchors; links to repository files go to GitHub.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = 'https://github.com/khandelwalkshitij/project-wednesday/blob/main/';
export const PAGES = [['models', 'Overview and models'], ['config-reference', 'Config reference'], ['accuracy', 'Accuracy and limits'], ['glossary', 'Glossary']];

export const slug = t => t.toLowerCase().replace(/<[^>]+>/g, '').replace(/[^a-z0-9 _-]/g, '').trim().replace(/ /g, '-');
const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function link(href, page) {
  if (/^https?:/.test(href)) return [href, true];
  let m = /^([\w-]+)\.md(?:#([\w-]+))?$/.exec(href);
  if (m && PAGES.some(p => p[0] === m[1])) return ['#' + m[1] + (m[2] ? '--' + m[2] : ''), false];
  if (m) return [REPO + 'docs/' + href, true];                                           // a page not in the tab: GitHub
  if (href[0] === '#') return ['#' + page + '--' + href.slice(1), false];
  return [REPO + path.posix.normalize('docs/' + href), true];                           // a file in the repository
}

export function inline(s, page) {
  const code = [];
  s = s.replace(/`([^`]+)`/g, (_, c) => { code.push('<code>' + esc(c) + '</code>'); return '\u0000' + (code.length - 1) + '\u0000'; });
  s = s.replace(/&(?![a-zA-Z#][a-zA-Z0-9]*;)/g, '&amp;').replace(/<(?![a-zA-Z/])/g, '&lt;');   // keep inline HTML, escape stray < and &
  s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, t, h) => { const [u, ext] = link(h, page); return '<a href="' + u + '"' + (ext ? ' target="_blank" rel="noopener"' : ' data-doc') + '>' + t + '</a>'; });
  s = s.replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>').replace(/(^|[\s(])\*([^*\s][^*]*)\*/g, '$1<i>$2</i>');
  return s.replace(/\u0000(\d+)\u0000/g, (_, i) => code[+i]);
}

const cells = l => l.trim().replace(/^\||\|$/g, '').split('|').map(c => c.trim());

export function render(md, page) {
  const lines = md.replace(/\r/g, '').split('\n'), out = [];
  let i = 0;
  while (i < lines.length) {
    const l = lines[i];
    if (!l.trim()) { i++; continue; }
    let m;
    if ((m = /^```(\w*)/.exec(l))) {
      const body = []; i++;
      while (i < lines.length && !lines[i].startsWith('```')) body.push(lines[i++]);
      i++; out.push('<pre><code>' + esc(body.join('\n')) + '</code></pre>'); continue;
    }
    if ((m = /^(#{1,4}) (.*)$/.exec(l))) {
      const n = m[1].length, id = n === 1 ? page : page + '--' + slug(m[2]);
      out.push('<h' + (n + 1) + ' id="' + id + '">' + inline(m[2], page) + '</h' + (n + 1) + '>'); i++; continue;
    }
    if (l.startsWith('|') && /^\|[\s|:-]+\|$/.test((lines[i + 1] || '').trim())) {
      const head = cells(l); i += 2; const rows = [];
      while (i < lines.length && lines[i].startsWith('|')) rows.push(cells(lines[i++]));
      out.push('<div class="doc-tablewrap"><table class="doc-table"><tr>' + head.map(h => '<th>' + inline(h, page) + '</th>').join('') + '</tr>' +
        rows.map(r => '<tr>' + r.map(c => '<td>' + inline(c, page) + '</td>').join('') + '</tr>').join('') + '</table></div>'); continue;
    }
    if (/^- /.test(l)) {
      const items = [];
      while (i < lines.length && /^- /.test(lines[i])) items.push(lines[i++].slice(2));
      out.push('<ul>' + items.map(t => '<li>' + inline(t, page) + '</li>').join('') + '</ul>'); continue;
    }
    if (/^<\w/.test(l)) { out.push(l); i++; continue; }                                   // a block of raw HTML
    const para = [];
    while (i < lines.length && lines[i].trim() && !/^(```|#{1,4} |- |\||<\w)/.test(lines[i])) para.push(lines[i++]);
    out.push('<p>' + inline(para.join(' '), page) + '</p>');
  }
  return out.join('\n');
}

export function build() {
  const read = n => fs.readFileSync(path.join(root, 'docs', n + '.md'), 'utf8');
  const toc = '<p>Pages: ' + PAGES.map(([n, t]) => '<a href="#' + n + '" data-doc>' + t + '</a>').join(' | ') + '</p>';
  const html = toc + '\n<hr>\n' + PAGES.map(([n]) => '<section>\n' + render(read(n), n) + '\n</section>').join('\n<hr>\n');
  const js = '// Generated by tools/build-docs.mjs from docs/*.md. Do not edit: change the Markdown and run npm run docs.\nexport var DOC_HTML = ' + JSON.stringify(html) + ';\n';
  // field list: the "Field summary" table of the config reference
  const ref = read('config-reference'), s0 = ref.indexOf('## Field summary'), sec = ref.slice(s0, ref.indexOf('\n## ', s0 + 1)), rows = sec.split('\n').filter(l => l.startsWith('| `'));
  const dl = rows.map(r => { const [f, d] = cells(r); return '          <dt>' + inline(f, 'config-reference') + '</dt><dd>' + inline(d, 'config-reference') + '</dd>'; }).join('\n');
  const htmlPath = path.join(root, 'index.html'), page = fs.readFileSync(htmlPath, 'utf8');
  const a = page.indexOf('<!-- config-fields:start'), b = page.indexOf('<!-- config-fields:end -->');
  if (a < 0 || b < 0) throw new Error('index.html: config-fields markers not found');
  const start = page.indexOf('-->', a) + 3;
  const index = page.slice(0, start) + '\n' + dl + '\n          <dt>More</dt><dd>Every field, with examples, and the plan.csv format: <a href="#config-reference" data-doc>Documentation tab, Config reference</a>.</dd>\n          ' + page.slice(b);
  return { js, index };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const { js, index } = build(), jsPath = path.join(root, 'src/viewer/docs-content.js'), htmlPath = path.join(root, 'index.html');
  if (process.argv.includes('--check')) {
    const stale = [[jsPath, js], [htmlPath, index]].filter(([p, t]) => !fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== t).map(([p]) => path.relative(root, p));
    if (stale.length) { console.error('out of date: ' + stale.join(', ') + ' (run npm run docs)'); process.exit(1); }
    console.log('docs up to date');
  } else { fs.writeFileSync(jsPath, js); fs.writeFileSync(htmlPath, index); console.log('wrote src/viewer/docs-content.js and the field list in index.html'); }
}
